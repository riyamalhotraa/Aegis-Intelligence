# ============================================================================
# APPROVE / REJECT REQUEST
# ============================================================================
#
# IMPORTANT:
# There is ONLY ONE decision route in this file.
#
# When a request is manually approved:
#
#     request
#       ↓
#     approved
#       ↓
#     create payment
#       ↓
#     backend generates transaction_id
#       ↓
#     /transactions can see it
#
# The transaction_id is NOT generated by React.
# ============================================================================

@app.post("/requests/{request_id}/decision")
def make_decision(
    request_id: str,
    body: DecisionRequest,
):
    decision = body.decision.lower().strip()

    if decision not in {"approved", "rejected"}:
        raise HTTPException(
            status_code=400,
            detail="Decision must be 'approved' or 'rejected'.",
        )

    # Update the original request first.
    updated = decide_request(
        request_id,
        decision,
    )

    if updated is None:
        raise HTTPException(
            status_code=404,
            detail="Payment request not found.",
        )

    # ------------------------------------------------------------------------
    # APPROVED
    # ------------------------------------------------------------------------
    #
    # Creating the payment record automatically creates a transaction ID
    # inside x402/payment_service.py.
    #
    # Example:
    #
    # payment_id     = UUID
    # transaction_id = TX-A1B2C3D4
    #
    # No fake transaction ID is generated in the frontend.
    # ------------------------------------------------------------------------

    if decision == "approved":

        try:
            payment = create_payment_request(
                request_id=request_id,
                task=updated.get(
                    "task",
                    "Approved payment request",
                ),
                provider=updated.get(
                    "provider",
                    "Unknown Provider",
                ),
                api=updated.get(
                    "api",
                    "x402 Payment API",
                ),
                amount=float(
                    updated.get(
                        "amount",
                        0,
                    )
                ),
            )

        except Exception as exc:
            print(
                "❌ PAYMENT CREATION FAILED:",
                repr(exc),
            )

            raise HTTPException(
                status_code=500,
                detail=f"Payment creation failed: {str(exc)}",
            )

        print(
            "✅ PAYMENT CREATED:",
            payment.get("payment_id"),
        )

        print(
            "🔗 TRANSACTION CREATED:",
            payment.get("transaction_id"),
        )

        return {
            **updated,

            "payment_created": True,

            "payment_id": payment.get(
                "payment_id"
            ),

            "transaction_id": payment.get(
                "transaction_id"
            ),

            "payment_status": payment.get(
                "status"
            ),

            "payment": payment,
        }

    # ------------------------------------------------------------------------
    # REJECTED
    # ------------------------------------------------------------------------

    return {
        **updated,

        "payment_created": False,

        "payment_id": None,

        "transaction_id": None,

        "payment_status": None,
    }


