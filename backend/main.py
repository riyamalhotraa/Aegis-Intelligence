@app.post("/x402/payment")
def create_x402_payment(
    request: PaymentRequest,
):
    """
    Create an x402-style payment request.

    IMPORTANT:
    transaction_id is intentionally NOT supplied here.

    payment_service.py generates it on the backend.
    """

    try:

        payment = create_payment_request(
            request_id=request.request_id,
            task=request.task,
            provider=request.provider,
            api=request.api,
            amount=request.amount,
        )

    except Exception as exc:

        print(
            "❌ x402 PAYMENT CREATION FAILED:",
            repr(exc),
        )

        raise HTTPException(
            status_code=500,
            detail=f"Payment creation failed: {str(exc)}",
        )

    return {
        "status": 402,
        "message": "Payment Required",
        "payment": payment,
    }


