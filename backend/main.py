@app.post(
    "/x402/execute/{payment_id}"
)
def execute_x402_payment(
    payment_id: str,
):

    payment = get_payment(
        payment_id
    )

    if payment is None:

        raise HTTPException(
            status_code=404,
            detail="Payment not found",
        )

    if payment["status"] != "settled":

        raise HTTPException(
            status_code=400,
            detail="Payment has not been settled.",
        )

    return {
        "success": True,

        "payment_id":
            payment_id,

        "transaction_hash":
            payment["transaction_hash"],

        "provider":
            payment["provider"],

        "api":
            payment["api"],

        "task":
            payment["task"],

        "message":
            "Payment settled. Service execution authorized.",
    }


